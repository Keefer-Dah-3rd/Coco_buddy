#!/usr/bin/env python3
"""Builds design/figma/plugin/code.js from design/figma/tokens-bridge.js (the one copy of the
Figma-side logic) plus the plugin's message handling. `--check` fails if code.js is stale."""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BRIDGE = ROOT / "design" / "figma" / "tokens-bridge.js"
OUTPUT = ROOT / "design" / "figma" / "plugin" / "code.js"

GLUE = """
// --- Plugin entry point -------------------------------------------------------
figma.showUI(__html__, { width: 440, height: 400, themeColors: true });
figma.ui.onmessage = async msg => {
  try {
    if (msg.type === 'export') {
      figma.ui.postMessage({ type: 'exported', result: await exportTokens() });
    } else if (msg.type === 'import') {
      const parsed = JSON.parse(msg.json);
      figma.ui.postMessage({ type: 'imported', report: await importTokens(parsed.tokens || parsed) });
    }
  } catch (error) {
    figma.ui.postMessage({ type: 'error', message: String((error && error.message) || error) });
  }
};
"""


def build():
    return ("// GENERATED by scripts/tokens/build_plugin.py from design/figma/tokens-bridge.js — do not edit.\n\n"
            + BRIDGE.read_text() + GLUE)


if __name__ == "__main__":
    code = build()
    if "--check" in sys.argv:
        if not OUTPUT.exists() or OUTPUT.read_text() != code:
            print("design/figma/plugin/code.js is out of date — run scripts/tokens/build_plugin.py", file=sys.stderr)
            sys.exit(1)
        print("Plugin is up to date.")
    else:
        OUTPUT.write_text(code)
        print(f"Wrote {OUTPUT.relative_to(ROOT)}")
